# 정렬 옵션
SORT_OPTIONS = {
    "유명한 순":   lambda k: CATALOG[k]["fame"],
    "공격적인 순": lambda k: -CATALOG[k]["risk"],
    "안전한 순":   lambda k: CATALOG[k]["risk"],
    "이름순":      lambda k: CATALOG[k]["name"],
}

def keys_by_category():
    """카테고리별 전략 키 묶음."""
    out = {}
    for cat in CATEGORY_ORDER:
        out[cat] = [k for k, v in CATALOG.items() if v["category"] == cat]
    return out

def sorted_keys(sort_by="유명한 순"):
    fn = SORT_OPTIONS.get(sort_by, SORT_OPTIONS["유명한 순"])
    return sorted(CATALOG.keys(), key=fn)

def meta(key):
    return CATALOG.get(key, CATALOG["composite"])
