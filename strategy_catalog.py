def detail(key):
    """전략의 정확한 작동 논리 + 근거 (상세 설명). 없으면 desc 폴백.

    detail 값이 (실수로) 튜플/리스트여도 안전하게 문자열로 합쳐 반환한다.
    """
    m = CATALOG.get(key)
    if not m:
        return ""
    d = m.get("detail")
    if isinstance(d, (tuple, list)):
        d = "".join(str(x) for x in d)
    return d or m.get("desc", "")


